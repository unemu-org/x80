#[test]
fn literal_sets_partition_each_table_into_instructions_holes_and_dispatch() {
    let mut logical_encodings = 0;
    for table in TABLES {
        let mut occurrences = [0; 256];
        for &key in table
            .documented
            .iter()
            .chain(table.undocumented)
            .chain(table.dispatch)
        {
            occurrences[usize::from(key)] += 1;
        }
        assert_eq!(occurrences, [1; 256], "{table:?}");
        logical_encodings += table.documented.len();
    }
    // Decision-20 §3 adds 8 CB and 225 terminals per indexed-CB selector.
    assert_eq!(logical_encodings, 1780);
}

#[test]
fn every_admitted_encoding_completes_one_step_from_neutral_state() {
    for table in TABLES {
        for &key in table.documented {
            let mut cpu = Z80::new(
                Registers {
                    pc: 0x1000,
                    sp: 0x9000,
                    ..Registers::default()
                },
                Latches::default(),
            );
            let mut bus = RecordingBus::new();
            let mut bytes = table.prefix.to_vec();
            bytes.extend([key, 0x00, 0x20]);
            bus.load(0x1000, &bytes);
            bus.inputs.push_back(0x42);
            let report = cpu.step(&mut bus);
            assert_eq!(report.exit, Exit::Budget, "{:02X?} {key:02X}", table.prefix);
            assert_eq!(report.steps, 1, "{:02X?} {key:02X}", table.prefix);
            assert!(report.cycles > 0, "{:02X?} {key:02X}", table.prefix);
        }
    }
}

